// Parses the comments on the status board (#17): status, dispatch and heartbeat comments in
// the format of docs/orchestrator.md, plus the looser free text sessions wrote before it.
// Pure: text in, records out.

export const ROLES = ['orchestrator', 'understudy', 'reviewer', 'conductor', 'builder', 'simplifier', 'design lead', 'phone lab', 'phone-PR upkeep', 'findings']
export const STATES = ['working', 'waiting', 'blocked', 'idle', 'stopped']
const CLOUD_FOOTER = /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_/

// Keys of the old bullet style ("- **Goal:** ...") mapped onto the format's keys.
const KEY_ALIASES = {
  goal: 'working on',
  issue: 'working on',
  'working on': 'working on',
  shipped: 'done',
  'shipped for review': 'done',
  done: 'done',
  'done since last status': 'done',
  next: 'next',
  blocked: 'blocked',
  branch: 'where',
  'branch / worktree': 'where',
  'branch / pr': 'where',
  'branches': 'where',
  where: 'where',
  role: 'role',
  state: 'state',
  asks: 'asks',
  by: 'by',
  session: 'session',
  'next tick': 'next tick',
  since: 'since',
}

/** "Every" key: value line of a comment, keys lower-cased, markdown bullets and bold removed. */
export function keyLines(body) {
  const out = {}
  for (const raw of String(body).split(/\r?\n/)) {
    const line = raw.replace(/^\s*[-*]\s+/, '').replace(/\*\*([^*]+?):\*\*/, '$1:').replace(/^\*\*([^*]+?)\*\*:/, '$1:').trim()
    const m = /^([A-Za-z][A-Za-z /-]{0,30}?):\s*(.*)$/.exec(line)
    if (!m) continue
    const key = KEY_ALIASES[m[1].toLowerCase().trim()]
    if (key && out[key] === undefined) out[key] = m[2].trim()
  }
  return out
}

const firstLine = (body) => String(body).split(/\r?\n/, 1)[0].trim()
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const isNone = (v) => v === undefined || /^(none|no|n\/a|-|nothing)\b/i.test(v.trim())

/** Which kind of board comment this is, by its first line. */
export function commentKind(body) {
  const first = firstLine(body)
  if (/^heartbeat:/i.test(first)) return 'heartbeat'
  if (/^dispatch:/i.test(first)) return 'dispatch'
  if (/^lab-window:/i.test(first)) return 'lab-window'
  if (/^status:/i.test(first) || /^\*\*status\b/i.test(first)) return 'status'
  return 'other'
}

/** Name and surface from the first line: "status: cloud-5 · claude/x", "**Status (cloud builder, overnight)**". */
export function nameFromFirstLine(first) {
  let m = /^(?:status|dispatch|heartbeat):\s*([A-Za-z0-9][A-Za-z0-9_.-]*)/i.exec(first)
  if (m) return m[1].toLowerCase()
  m = /^\*\*status\s*\(([^,):]+)/i.exec(first)
  if (m) return slug(m[1])
  return null
}

export function roleFromName(name) {
  const n = name || ''
  if (/orchestr|^dev-\d+/.test(n)) return 'orchestrator'
  if (/understudy/.test(n)) return 'understudy'
  if (/review/.test(n)) return 'reviewer'
  if (/conductor/.test(n)) return 'conductor'
  if (/simplif/.test(n)) return 'simplifier'
  if (/phone-prs?\b|phone-pr-|upkeep/.test(n)) return 'phone-PR upkeep'
  if (/phone-lab/.test(n)) return 'phone lab'
  if (/design/.test(n)) return 'design lead'
  if (/findings/.test(n)) return 'findings'
  return 'builder'
}

function normaliseRole(value, name) {
  if (value) {
    const v = value.toLowerCase().trim()
    const hit = ROLES.find((r) => r.toLowerCase() === v || r.toLowerCase().replace(/[^a-z]/g, '') === v.replace(/[^a-z]/g, ''))
    if (hit) return hit
  }
  return roleFromName(name)
}

/** The state, given in the format or read from the old free text. */
export function inferState(keys, first) {
  if (keys.state) {
    const s = keys.state.toLowerCase().match(/[a-z]+/)?.[0]
    if (STATES.includes(s)) return s
  }
  const next = keys.next || ''
  const working = keys['working on'] || ''
  if (/\bstop(ping|ped)\b/i.test(first) || /(^|[;.,]\s*)(stopping|this session stops|stops here)|\bsession stops\b|^stopping\b/i.test(next) || /^(stopped|stopping)\b/i.test(working)) return 'stopped'
  if (!isNone(keys.blocked) && keys.blocked !== undefined && !/^none\b/i.test(keys.blocked)) return 'blocked'
  if (/^idle\b/i.test(working) || /·\s*idle\b/i.test(first)) return 'idle'
  if (/\b(waiting|watching)\b/i.test(working) || /^(wait|waiting)\b/i.test(next)) return 'waiting'
  return 'working'
}

const ISSUE_RE = /#(\d{1,6})\b/g
export const numbersIn = (text) => [...String(text || '').matchAll(ISSUE_RE)].map((m) => Number(m[1]))

/** PR numbers named in a text: "PR #N", "PRs #a, #b", ".../pull/N". */
export function prsIn(text) {
  const t = String(text || '')
  const out = new Set()
  for (const m of t.matchAll(/\/pull\/(\d+)/g)) out.add(Number(m[1]))
  for (const m of t.matchAll(/\bPRs?\s+((?:#\d+(?:\s*(?:,|and|→|->|then|\+)\s*)?)+)/gi)) for (const n of numbersIn(m[1])) out.add(n)
  return [...out]
}

export function branchesIn(text) {
  return [...new Set([...String(text || '').matchAll(/\bclaude\/[A-Za-z0-9._/-]*[A-Za-z0-9]/g)].map((m) => m[0]))]
}

export function branchIn(text) {
  return /\bclaude\/[A-Za-z0-9._/{}-]*[A-Za-z0-9}]/.exec(String(text || ''))?.[0] ?? null
}

/**
 * One status comment as a record, or null if it is not one.
 * comment: { id, created_at, updated_at, body, html_url? }
 */
export function parseStatus(comment) {
  const body = String(comment.body || '')
  if (commentKind(body) !== 'status') return null
  const first = firstLine(body)
  const keys = keyLines(body.split(/\r?\n/).slice(1).join('\n'))
  const name = nameFromFirstLine(first) || 'unnamed'
  const formatted = keys.role !== undefined && keys.state !== undefined
  const cloud = /\(cloud\)|\bcloud\b/i.test(first) || /^cloud-/.test(name) || CLOUD_FOOTER.test(body)
  const where = keys.where || first.split('·').slice(1).join('·').trim() || ''
  const working = keys['working on'] || ''
  const asks = isNone(keys.asks) ? null : keys.asks
  const blocked = keys.blocked === undefined || /^none\b/i.test(keys.blocked) ? null : keys.blocked
  const prs = prsIn([keys.where, working, keys.done, first].join('\n'))
  return {
    id: name,
    name,
    kind: name.startsWith('agent-') ? 'agent' : normaliseRole(keys.role, name) === 'orchestrator' ? 'orchestrator' : 'session',
    surface: cloud ? 'cloud' : 'local',
    role: normaliseRole(keys.role, name),
    state: inferState(keys, first),
    where: where || null,
    branch: branchIn(where) || branchIn(first) || branchIn(working),
    branches: branchesIn([first, where, working].join('\n')),
    working_on: working || null,
    issue: numbersIn(working)[0] ?? numbersIn(first)[0] ?? null,
    prs,
    done: keys.done || null,
    next: keys.next || null,
    blocked,
    asks,
    formatted,
    at: comment.created_at,
    comment_id: comment.id,
    url: comment.html_url || null,
    body,
  }
}

/** A dispatch comment, or null. */
export function parseDispatch(comment) {
  const body = String(comment.body || '')
  if (commentKind(body) !== 'dispatch') return null
  const first = firstLine(body)
  const keys = keyLines(body.split(/\r?\n/).slice(1).join('\n'))
  const name = nameFromFirstLine(first)
  if (!name) return null
  return {
    name,
    surface: /\(local\)/.test(first) ? 'local' : 'cloud',
    role: normaliseRole(keys.role, name),
    issues: numbersIn(keys['working on']),
    by: keys.by || null,
    at: comment.created_at,
    comment_id: comment.id,
  }
}

/** A heartbeat comment, or null. Its time is updated_at: the comment is edited in place. */
export function parseHeartbeat(comment) {
  const body = String(comment.body || '')
  if (commentKind(body) !== 'heartbeat') return null
  const who = /^heartbeat:\s*([a-z-]+)/i.exec(firstLine(body))?.[1]?.toLowerCase()
  if (!who) return null
  const keys = keyLines(body.split(/\r?\n/).slice(1).join('\n'))
  const state = (keys.state || 'active').trim()
  const away = /^away\s+until\s+(.+)$/i.exec(state)
  return {
    who,
    session: keys.session || null,
    state: away ? 'away' : state.split(/\s/)[0].toLowerCase(),
    away_until: away ? away[1].trim() : null,
    next_tick_min: keys['next tick'] ? Number.parseInt(keys['next tick'], 10) || null : null,
    at: comment.updated_at || comment.created_at,
    comment_id: comment.id,
  }
}

/** "lab-window: until 11:30 UTC" posted at `at`: the end of the window as an ISO time, or null. */
export function parseLabWindow(comment) {
  const m = /^lab-window:\s*(?:until\s+)?(\d{1,2}):(\d{2})\s*(?:UTC|Z)?\s*$/i.exec(firstLine(comment.body || ''))
  if (!m) return null
  const at = new Date(comment.created_at)
  const end = new Date(Date.UTC(at.getUTCFullYear(), at.getUTCMonth(), at.getUTCDate(), Number(m[1]), Number(m[2])))
  if (end <= at) end.setUTCDate(end.getUTCDate() + 1)
  return { opened_at: comment.created_at, until: end.toISOString(), comment_id: comment.id }
}

/** The "Decision needed:" block of a comment, or null. */
export function parseDecision(body) {
  const text = String(body || '')
  const q = /^\s*\**Decision needed:?\**:?\s*(.+)$/im.exec(text)
  if (!q) return null
  const rec = /^\s*\**Recommendation:?\**:?\s*(.+)$/im.exec(text)
  const opt = /^\s*\**Options:?\**:?\s*(.+)$/im.exec(text)
  const options = opt ? opt[1].split(/\s*(?=\([a-z]\)\s)/).map((o) => o.trim()).filter(Boolean) : []
  return { question: q[1].trim(), recommendation: rec ? rec[1].trim() : null, options }
}

/** Verdict and phone-result lines on a PR comment. */
export function parsePrComment(comment) {
  const first = firstLine(comment.body || '')
  let m = /^verdict:\s*(approve|changes)\s+([0-9a-f]{7,40})/i.exec(first)
  if (m) return { type: 'verdict', verdict: m[1].toLowerCase(), sha: m[2].toLowerCase(), at: comment.created_at }
  m = /^phone-result:\s*(pass|fail)\s+([0-9a-f]{7,40})\s*(?:·\s*(.*))?$/i.exec(first)
  if (m) return { type: 'phone-result', result: m[1].toLowerCase(), sha: m[2].toLowerCase(), text: m[3] || '', at: comment.created_at }
  m = /^claude-loop:\s*claimed by\s+([^\s,]+)/i.exec(first)
  if (m) return { type: 'claim', who: m[1], at: comment.created_at }
  m = /^claude-loop:\s*released/i.exec(first)
  if (m) return { type: 'release', at: comment.created_at }
  return null
}
